func IsInstanceKey(key string) bool {
	return slices.Contains(InstanceKeys, key)
}

func InstanceKeysOf(keys []string) []string {
	var out []string
	for _, key := range keys {
		if IsInstanceKey(key) && !slices.Contains(out, key) {
			out = append(out, key)
		}
	}
	return out
}
